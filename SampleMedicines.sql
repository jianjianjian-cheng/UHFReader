SELECT '药品基础数据导入完成！' AS '提示';
SELECT COUNT(*) AS '药品总数' FROM Medicines;
SELECT '药品分类统计：' AS '';
SELECT '类别', COUNT(*) AS '数量' FROM (
    SELECT '抗生素类' AS '类别' WHERE Id BETWEEN 1 AND 5
    UNION ALL
    SELECT '解热镇痛类' WHERE Id BETWEEN 6 AND 10
    UNION ALL
    SELECT '维生素类' WHERE Id BETWEEN 11 AND 15
    UNION ALL
    SELECT '心脑血管类' WHERE Id BETWEEN 16 AND 20
    UNION ALL
    SELECT '消化系统类' WHERE Id BETWEEN 21 AND 25
    UNION ALL
    SELECT '呼吸系统类' WHERE Id BETWEEN 26 AND 30
    UNION ALL
    SELECT '糖尿病类' WHERE Id BETWEEN 31 AND 35
    UNION ALL
    SELECT '外用药类' WHERE Id BETWEEN 36 AND 40
) AS Categories GROUP BY 类别;
